func TestUMIDReferenceReportAndResponse(t *testing.T) {
	// Fixed section generated by reference 806c61f, including all 43 fields.
	sum := sha256.Sum256([]byte("qoder-umid-fixture-user#0"))
	section, hostname := buildUMIDSection1B(sum, time.UnixMilli(1_790_000_000_000))
	digest := sha256.Sum256(section)
	if len(section) != 560 || hex.EncodeToString(digest[:]) != "3b20c445205b7d31933e47077a3de6e56ea0d04f4e3d96898ebd9de8d10fb102" || hostname != "qoder-0bb22ae0" {
		t.Fatal("UMID field layout or block encoding differs from the reference report")
	}
	token, err := decryptUMIDResponseDT("AQWQ4eIMHDiURmmVA0awEeQpLa8k3G2kVCGu3TzzikBRBzOtZazWbMFmqK+EXXNTqg==")
	if err != nil || token != "fixture-machine-token" {
		t.Fatal("reference response fixture was not decrypted correctly")
	}
}


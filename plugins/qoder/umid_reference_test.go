func TestUMIDAccountCacheAndExpiry(t *testing.T) {
	sa, other := fixtureIntlAuth(t), fixtureIntlAuth(t)
	calls := 0
	stubUMID(t, func(req *http.Request) (*hostHTTPResponse, error) {
		calls++
		if req.URL.String() != endpointUMIDRepPc || req.Method != http.MethodPost || req.Header.Get("Content-Type") != "text/plain;charset=UTF-8" || req.Header.Get("User-Agent") != umidUserAgent {
			t.Fatal("UMID issuance request differs from reference")
		}
		if req.Header.Get("Authorization") != "" || req.Header.Get("Cookie") != "" {
			t.Fatal("UMID collector must not receive account credentials")
		}
		return &hostHTTPResponse{StatusCode: http.StatusOK, Body: []byte(testUMIDIssuedPayload)}, nil
	})
	first, err := resolveAccountUMID(sa)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := resolveAccountUMID(sa); err != nil || calls != 1 {
		t.Fatal("account identity was not reused within its cache lifetime")
	}
	second, err := resolveAccountUMID(other)
	if err != nil || calls != 2 || first.MachineID == second.MachineID || first.MachineHostname == second.MachineHostname {
		t.Fatal("two accounts shared the same identity seed or cache entry")
	}
	if first.MachineID != uuid.NewSHA1(uuid.NameSpaceDNS, []byte(sa.Account.UID+"#0")).String() || first.MachineOS != "x86_64_linux" || first.MachineToken != "fixture-machine-token" {
		t.Fatal("identity seed/platform differs from reference")
	}
	key := accountUMIDKey(sa)
	v, _ := umidCache.Load(key)
	entry := *v.(*umidCacheEntry)
	entry.fetchedAt = time.Now().Add(-umidCacheTTL - time.Second)
	umidCache.Store(key, &entry)
	if _, err := resolveAccountUMID(sa); err != nil || calls != 3 {
		t.Fatal("expired UMID was not renewed")
	}
}

func TestUMIDRejectsInvalidIssuance(t *testing.T) {
	for _, body := range []string{`{}`, `{"ec":500}`, `{"ec":200,"dt":"bad"}`, `{"ec":200,"dt":"AA=="}`} {
		sa := fixtureIntlAuth(t)
		stubUMID(t, func(*http.Request) (*hostHTTPResponse, error) {
			return &hostHTTPResponse{StatusCode: http.StatusOK, Body: []byte(body)}, nil
		})
		if _, err := resolveAccountUMID(sa); err == nil {
			t.Fatal("invalid UMID issuance accepted")
		}
		if _, exists := umidCache.Load(accountUMIDKey(sa)); exists {
			t.Fatal("failed issuance populated the cache")
		}
	}
	badIndex := base64.StdEncoding.EncodeToString(append([]byte{11}, make([]byte, 16)...))
	if _, err := decryptUMIDResponseDT(badIndex); err == nil {
		t.Fatal("out-of-range response key accepted")
	}
}

func TestIntlCampaignReadAndClaimShareUMID(t *testing.T) {
	previousMemo := roundMemo
	roundMemo = &campaignRoundMemo{perAccount: map[string]campaignRoundEntry{}, perRegion: map[string]campaignRoundEntry{}}
	t.Cleanup(func() { roundMemo = previousMemo })
	sa := fixtureIntlAuth(t)
	issued, requests := 0, 0
	stubUMID(t, func(*http.Request) (*hostHTTPResponse, error) {
		issued++
		return &hostHTTPResponse{StatusCode: http.StatusOK, Body: []byte(testUMIDIssuedPayload)}, nil
	})
	stubLoginTransport(t, func(req *http.Request) (*http.Response, error) {
		requests++
		wantID := uuid.NewSHA1(uuid.NameSpaceDNS, []byte(sa.Account.UID+"#0")).String()
		for name, value := range map[string]string{
			"Authorization": "Bearer dt-reference-fixture", "Accept": "application/json",
			"Content-Type": "application/json", "User-Agent": "Qoder",
			"Cosy-ClientType": "10", "Cosy-Version": "0.4.3",
			"Cosy-MachineId": wantID, "Cosy-MachineToken": "fixture-machine-token",
			"Cosy-MachineOS": "x86_64_linux",
		} {
			if req.Header.Get(name) != value {
				t.Fatalf("campaign %s header %s differs from reference", req.Method, name)
			}
		}
		for _, name := range []string{"Cosy-MachineType", "Cosy-MachineCode", "Cosy-MachineHostname"} {
			if req.Header.Get(name) == "" {
				t.Fatalf("missing campaign identity header %s", name)
			}
		}
		if req.URL.Path == "/sash/api/v1/me/campaigns" && req.Method == http.MethodGet {
			return loginJSON(http.StatusOK, campaignList("CLAIMABLE")), nil
		}
		if req.URL.Path == "/sash/api/v1/me/campaigns/camp-cn-daily/claim" && req.Method == http.MethodPost {
			return loginJSON(http.StatusOK, `{"status":"CLAIMED","benefit":{"kind":"CREDITS","amount":100}}`), nil
		}
		t.Fatal("unexpected campaign request or legacy session bootstrap")
		return nil, nil
	})
	status, err := fetchCampaignStatus(sa)
	if err != nil || len(status.Campaigns) != 1 {
		t.Fatal("campaign list failed")
	}
	result, err := claimCampaignByID(sa, &status.Campaigns[0])
	if err != nil || result["success"] != true || issued != 1 || requests != 2 {
		t.Fatal("campaign read and claim did not reuse the same issued identity")
	}
}

func TestIntlEmptyCampaignListDoesNotSwitchIdentity(t *testing.T) {
	sa := fixtureIntlAuth(t)
	stubUMID(t, func(*http.Request) (*hostHTTPResponse, error) {
		return &hostHTTPResponse{StatusCode: http.StatusOK, Body: []byte(testUMIDIssuedPayload)}, nil
	})
	requests := 0
	stubLoginTransport(t, func(req *http.Request) (*http.Response, error) {
		requests++
		if req.URL.Path != "/sash/api/v1/me/campaigns" || req.Header.Get("Cosy-MachineToken") == "" {
			t.Fatal("empty list triggered a legacy identity or launch-sync request")
		}
		return loginJSON(http.StatusOK, `{"showCampaign":false,"campaigns":[]}`), nil
	})
	status, err := fetchCampaignStatus(sa)
	if err != nil || len(status.Campaigns) != 0 || requests != 1 {
		t.Fatal("empty list must stay an authoritative single response")
	}
}

